export function localeFromPath(path) {
    return path === '/nl' || path.startsWith('/nl/') ? 'nl' : 'en';
}

export function message(locale, key, replacements = {}) {
    let text = messages[locale]?.[key] ?? messages.en[key] ?? key;
    for (const [name, value] of Object.entries(replacements)) {
        text = text.replaceAll(`{${name}}`, String(value));
    }
    return text;
}

export function useI18n() {
    const route = useRoute();
    const locale = computed(() => localeFromPath(route.path));

    function t(key, replacements = {}) {
        return message(locale.value, key, replacements);
    }

    function localizedPath(path) {
        if (locale.value !== 'nl') return path;
        if (path === '/' || path === '/nl/') return '/nl/';
        const clean = path.replace(/^\/nl(?=\/|$)/, '');
        return `/nl${clean.startsWith('/') ? clean : `/${clean}`}`;
    }

    function alternatePath(path, targetLocale) {
        const base = path.replace(/^\/nl(?=\/|$)/, '') || '/';
        return targetLocale === 'nl'
            ? `/nl${base === '/' ? '/' : base}`
            : base;
    }

    return { locale, t, localizedPath, alternatePath };
}
